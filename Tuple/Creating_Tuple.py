"""
Topic: Introduction to Tuples
Description: A Tuple is a collection used to store multiple items in a single variable.
Unlike Lists, Tuples are UNCHANGEABLE (Immutable). They use round brackets ().
"""

# Create a tuple containing student marks
marks_tuple = (78, 85, 92, 67, 74)

# Print the complete tuple
print("Student Marks Tuple:", marks_tuple)

# Check the data type
print("Data Type:", type(marks_tuple))
