"""
Topic: Iterating through a Tuple (Looping)
Description: You can loop through tuple items just like you do with lists.
"""

# Tuple of student marks
marks = (78, 85, 92, 67, 74)
print("Displaying marks one by one using a Loop:")
print("-" * 40)

# Loop through each item
for mark in marks:
    print(f"Student Mark: {mark}")
