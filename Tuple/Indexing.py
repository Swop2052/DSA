"""
Topic: Accessing Tuple Items (Indexing)
Description: Just like Lists, Tuple items are indexed starting from 0.
You can use square brackets [] to access them.
"""

# Initial tuple of student marks
marks = (78, 85, 92, 67, 74)
print("Full Tuple:", marks)
print("-" * 20)

# Access the first mark (Index 0)
print("First mark (Index 0):", marks[12])

