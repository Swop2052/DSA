"""
Topic: Iterating through a List (Looping)
Description: You can use a 'for' loop to go through each item in the list one by one.
This is useful for displaying all items or performing an action on each item.
"""

# Initial list of student marks
marks = [78, 85, 92, 67, 74]

print("Displaying each mark one by one:")
print("-" * 30)

# Take each mark one by one and print it
for mark in marks:
    print("Student Mark:", mark)