"""
Topic: Adding Elements to a List (append)
Description: The append() method adds a single item to the end of the list.
This is useful when you want to expand your list dynamically.
"""

# Initial list of student marks
marks = [78, 85, 92, 67, 74]
print("Original Marks:", marks)

# Add a new mark (88) at the very end of the list
marks.append(88)

# Display the list after appending
print("Marks after append(88):", marks)