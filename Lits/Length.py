"""
Topic: Finding the Length of a List (len)
Description: The len() function counts the total number of items present in the list.
"""

# Initial list of student marks
marks = [78, 85, 92, 67, 74]
print("Marks List:", marks)

# Use len() to count how many marks are in the list
total_items = len(marks)

print(f"There are a total of {total_items} marks in the list.")